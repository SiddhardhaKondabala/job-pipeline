#!/usr/bin/env bash
#
# bootstrap.sh — make the job-pipeline hub runnable against the two repos.
#
# Idempotent and safe to re-run: it only creates directories, writes .env when
# absent, and copies the canonical schemas into the bot. It installs repo
# dependencies ONLY when you pass --deps (those installs are large).
#
#   ./bootstrap.sh            # env + dirs + schema sync + tool check
#   ./bootstrap.sh --deps     # also run `npm install` / `uv sync` if missing
#
set -euo pipefail

HUB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HUB"

WANT_DEPS=0
[ "${1:-}" = "--deps" ] && WANT_DEPS=1

# Resolve a repo location: prefer a submodule inside the hub, else a sibling.
resolve() { # $1 = submodule dir name, $2 = sibling relative path
  if [ -e "$HUB/$1/.git" ]; then
    echo "$HUB/$1"
  elif [ -d "$HUB/$2" ]; then
    (cd "$HUB/$2" && pwd)
  else
    echo "$HUB/$2" # report the expected path even if missing, for the error below
  fi
}

CAREER_OPS_DIR="${CAREER_OPS_DIR:-$(resolve career-ops ../career-ops)}"
LINKEDIN_BOT_DIR="${LINKEDIN_BOT_DIR:-$(resolve linkedin-bot ../LinkedIn-AI-Job-Applier-Ultimate)}"
if [ -d "$HUB/../career-data" ]; then
  CAREER_OPS_ROOT="${CAREER_OPS_ROOT:-$(cd "$HUB/../career-data" && pwd)}"
else
  CAREER_OPS_ROOT="${CAREER_OPS_ROOT:-$HUB/../career-data}"
fi
CAREER_OPS_INTEGRATION_DIR="${CAREER_OPS_INTEGRATION_DIR:-$CAREER_OPS_ROOT/data/integrations}"

echo "==> Resolving repos"
err=0
if [ ! -d "$CAREER_OPS_DIR" ]; then
  echo "    MISSING career-ops at: $CAREER_OPS_DIR" >&2; err=1
else
  echo "    career-ops : $CAREER_OPS_DIR"
fi
if [ ! -d "$LINKEDIN_BOT_DIR" ]; then
  echo "    MISSING LinkedIn bot at: $LINKEDIN_BOT_DIR" >&2; err=1
else
  echo "    bot        : $LINKEDIN_BOT_DIR"
fi
if [ "$err" -ne 0 ]; then
  cat >&2 <<EOF

Point the hub at the repos and re-run:
  CAREER_OPS_DIR=/path/to/career-ops \\
  LINKEDIN_BOT_DIR=/path/to/LinkedIn-AI-Job-Applier-Ultimate \\
  ./bootstrap.sh
(Or add them as submodules named career-ops/ and linkedin-bot/ once you fork.)
EOF
  exit 1
fi

echo "==> Creating personal-data workspace (outside both repos)"
mkdir -p "$CAREER_OPS_INTEGRATION_DIR"
echo "    $CAREER_OPS_INTEGRATION_DIR"

if [ ! -f "$HUB/.env" ]; then
  echo "==> Writing .env (resolved, absolute)"
  cat > "$HUB/.env" <<EOF
# Generated by bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Edit freely.
CAREER_OPS_DIR="$CAREER_OPS_DIR"
LINKEDIN_BOT_DIR="$LINKEDIN_BOT_DIR"
CAREER_OPS_ROOT="$CAREER_OPS_ROOT"
CAREER_OPS_INTEGRATION_DIR="$CAREER_OPS_INTEGRATION_DIR"
LINKEDIN_APPROVED_QUEUE="linkedin-approved.json"
LINKEDIN_RESULTS="linkedin-results.jsonl"
CAREER_OPS_CLAIM_TIMEOUT_SECONDS="86400"
EOF
else
  echo "==> .env already exists — leaving it (delete it to regenerate)"
fi

echo "==> Checking tools"
for tool in node npm uv; do
  if command -v "$tool" >/dev/null 2>&1; then
    echo "    ok   $tool ($("$tool" --version 2>/dev/null | head -1))"
  else
    echo "    WARN $tool not found on PATH" >&2
  fi
done

if [ "$WANT_DEPS" -eq 1 ]; then
  echo "==> Installing dependencies (--deps)"
  if [ ! -d "$CAREER_OPS_DIR/node_modules" ]; then
    echo "    npm install (career-ops)"; (cd "$CAREER_OPS_DIR" && npm install)
  else
    echo "    career-ops node_modules present — skipping"
  fi
  if [ ! -d "$LINKEDIN_BOT_DIR/.venv" ]; then
    echo "    uv sync (bot)"; (cd "$LINKEDIN_BOT_DIR" && uv sync)
  else
    echo "    bot .venv present — skipping"
  fi
else
  echo "==> Skipping dependency install (pass --deps to install)"
fi

echo "==> Seeding bot config from examples (gitignored; needed to import/run the bot)"
for f in app_config.py search_config.yaml; do
  if [ ! -f "$LINKEDIN_BOT_DIR/config/$f" ] && [ -f "$LINKEDIN_BOT_DIR/examples/config/$f" ]; then
    cp "$LINKEDIN_BOT_DIR/examples/config/$f" "$LINKEDIN_BOT_DIR/config/$f"
    echo "    seeded config/$f"
  else
    echo "    config/$f present or no example — leaving it"
  fi
done

echo "==> Syncing canonical schemas into the bot"
"$HUB/scripts/sync-schemas.sh"

cat <<EOF

Bootstrap complete.

Next:
  make env            # show resolved paths
  make test           # schema drift check + both integration test suites
  make help           # all targets
EOF
